  async function submitAuth(e) {
    e.preventDefault();
    if (state.authBusy) return;
    const join = state.authMode === "join";
    const email = $("auth-email").value.trim().toLowerCase();
    const password = $("auth-password").value;
    const nick = $("auth-nick").value.trim();
    const invite = $("auth-invite").value.trim();
    document.querySelectorAll(".field-error").forEach((el) => el.classList.add("hidden"));
    let bad = false;
    const fail = (input, key) => {
      bad = true;
      const box = input.closest("label") || input.parentElement;
      const err = box.querySelector(".field-error");
      if (err) {
        err.textContent = t(key) || key;
        err.classList.remove("hidden");
      }
    };
    if (!EMAIL_RE.test(email)) fail($("auth-email"), "emailInvalid");
    if (password.length < 6 || password.length > 72) fail($("auth-password"), "passwordShort");
    if (join) {
      if (!NICK_RE.test(nick)) fail($("auth-nick"), "nickInvalid");
      if (password !== $("auth-confirm").value) fail($("auth-confirm"), "passwordMismatch");
      if (!invite) fail($("auth-invite"), "invalidInvite");
      if (!$("auth-agree").checked) fail($("field-agree"), "acceptTerms");
    }
    if (bad) return;
    state.authBusy = true;
    syncAuthBar();
    $("auth-submit").disabled = true;
    $("auth-submit").textContent = join ? t("creatingAccount") : t("loggingIn");
    $("auth-error").classList.add("hidden");
    try {
      const res = join
        ? await api("/auth/register", {
            method: "POST",
            body: JSON.stringify({ email, password, nick, inviteCode: invite }),
          })
        : await api("/auth/login", {
            method: "POST",
            body: JSON.stringify({ email, password }),
          });
      setToken(res.token);
      state.user = res.user;
      state.balance = res.balance;
      await hydrate();
      $("auth-password").value = "";
      $("auth-confirm").value = "";
      closeLogin();
    } catch (err) {
      $("auth-error").textContent = errMsg(err, join ? "joinFailed" : "loginFailed");
      $("auth-error").classList.remove("hidden");
    } finally {
      state.authBusy = false;
      syncAuthBar();
      $("auth-submit").disabled = false;
      paintAuthMode();
    }
  }

