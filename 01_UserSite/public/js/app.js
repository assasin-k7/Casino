  async function api(path, init = {}) {
    const headers = new Headers(init.headers || {});
    if (init.body && !headers.has("Content-Type")) headers.set("Content-Type", "application/json");
    if (state.token) headers.set("Authorization", `Bearer ${state.token}`);
    const res = await fetch(`/api${path}`, { ...init, headers });
    const text = await res.text();
    let data = null;
    try {
      data = text ? JSON.parse(text) : null;
    } catch {
      data = null;
    }
    if (!res.ok) {
      const raw = data?.message;
      const message = Array.isArray(raw) ? raw.join(", ") : typeof raw === "string" ? raw : "Request failed";
      const err = new Error(message);
      err.status = res.status;
      err.code = data?.code;
      throw err;
    }
    return data;
  }

  function errMsg(e, fallbackKey) {
    if (e?.code && AUTH_CODE[e.code]) return t(AUTH_CODE[e.code]);
    if (e?.message && AUTH_CODE[e.message]) return t(AUTH_CODE[e.message]);
    return e?.message || t(fallbackKey) || "Error";
  }

  function setToken(token) {
    state.token = token;
    if (token) localStorage.setItem(TOKEN_KEY, token);
    else localStorage.removeItem(TOKEN_KEY);
  }

  function publish() {
    document.dispatchEvent(new CustomEvent("linbet:session"));
    renderHeader();
    renderWalletPage();
    renderFairness();
    renderBets();
    renderTicker();
    renderChat();
    renderWalletModal();
  }

  async function hydrate() {
    try {
      if (state.token) {
        const me = await api("/auth/me");
        const [wallet, ledger, fairness, bets, chat] = await Promise.all([
          api("/wallet"),
          api("/wallet/ledger"),
          api("/fairness"),
          api("/feed/bets"),
          api("/chat"),
        ]);
        state.user = me.user;
        state.balance = wallet.balance;
        state.depositedToday = wallet.depositedToday;
        state.dailyDepositCap = wallet.dailyDepositCap;
        state.ledger = ledger || [];
        state.clientSeed = fairness.clientSeed;
        state.serverSeedHash = fairness.serverSeedHash;
        state.nonce = fairness.nonce;
        state.revealed = fairness.revealed?.serverSeed || "";
        state.liveBets = bets || [];
        state.chat = chat || [];
      } else {
        const [bets, chat] = await Promise.all([api("/feed/bets"), api("/chat")]);
        state.liveBets = bets || [];
        state.chat = chat || [];
      }
    } catch (e) {
      if (e.status === 401) {
        setToken(null);
        state.user = null;
      }
    }
    state.hydrated = true;
    publish();
    connectSocket();
    syncAuthBar();
  }

  function syncAuthBar() {
    const bar = $("auth-progress");
    if (!bar) return;
    bar.classList.toggle("hidden", state.hydrated && !state.authBusy);
  }

  let socket;
  function connectSocket() {
    if (typeof io !== "function") return;
    if (socket) socket.close();
    socket = io("/realtime", {
      auth: { token: state.token || "" },
      transports: ["websocket", "polling"],
    });
    socket.on("balance", (payload) => {
      if (typeof payload?.balance === "number") {
        state.balance = payload.balance;
        publish();
      }
    });
    socket.on("bet", (bet) => {
      state.liveBets = [bet, ...state.liveBets.filter((b) => b.id !== bet.id)].slice(0, 40);
      renderBets();
      renderTicker();
    });
    socket.on("chat", (msg) => {
      if (!state.chat.some((c) => c.id === msg.id)) state.chat = [...state.chat, msg].slice(-80);
      renderChat();
    });
    socket.on("crash", (crash) => {
      document.dispatchEvent(new CustomEvent("linbet:crash", { detail: crash }));
    });
  }

